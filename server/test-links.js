const assert=require('node:assert/strict');
const {scopeOf,validOrigin,connectionInfo,invitation}=require('./links');
for(const host of ['127.0.0.1','localhost','[::1]'])assert.equal(scopeOf(host),'local');
for(const host of ['10.0.0.2','192.168.1.3','172.16.1.4','172.31.1.4'])assert.equal(scopeOf(host),'lan');
assert.equal(scopeOf('badminton.example.com'),'public');
assert.equal(scopeOf('172.32.1.4'),'public');
assert.equal(validOrigin('ws://127.0.0.1:8765/ws'),null);
assert.equal(validOrigin('https://user:password@example.com'),null);
const req={headers:{host:'127.0.0.1:8765'},socket:{}};
const local=connectionInfo(req,8765,'',{});
assert.equal(invitation(local,'ABC123'),'');
const lan=connectionInfo(req,8765,'',{LAN:[{address:'192.168.1.8',family:'IPv4',internal:false}]});
assert.equal(lan.scope,'lan');
assert.equal(invitation(lan,'ABC123'),'');
assert.equal(invitation({scope:'public',base:'http://badminton.example.com'},'ABC123'),'');
const pub=connectionInfo(req,8765,'https://badminton.example.com',{});
assert.equal(pub.scope,'public');
assert.equal(invitation(pub,'ABC123'),'https://badminton.example.com/index.html?room=ABC123');
console.log('PASS: invitation URLs, public/LAN/local scopes, no loopback share, configured domain.');
