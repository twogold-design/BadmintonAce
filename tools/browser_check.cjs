const { chromium } = require('playwright');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const {pathToFileURL} = require('node:url');
(async()=>{
  const root=path.resolve(__dirname,'..');
  fs.mkdirSync(path.join(root,'artifacts'),{recursive:true});
  const context=await chromium.launchPersistentContext(path.join(root,'.runtime','browser-test'),{executablePath:process.env.ACE_BROWSER||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,viewport:{width:1440,height:900},args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader','--autoplay-policy=no-user-gesture-required','--disable-crash-reporter','--disable-breakpad']});
  const page=await context.newPage();
  const errors=[];
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text()); console.log('BROWSER',m.text().slice(0,700));});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(root,'index.html')).href);
  await page.waitForFunction(()=>window.badmintonState?.screen==='menu',null,{timeout:30000});
  await page.screenshot({path:path.join(root,'artifacts','menu.png')});
  console.log('STATE',await page.evaluate(()=>window.badmintonState));
  await page.mouse.click(170,735);
  await page.waitForTimeout(400);
  await page.screenshot({path:path.join(root,'artifacts','help.png')});
  await page.mouse.click(1170,802);
  await page.waitForTimeout(200);
  await page.mouse.click(200,585);
  await page.waitForTimeout(500);
  if(!(await page.evaluate(()=>window.badmintonState.baseline_camera)))await page.keyboard.press('c');
  await page.waitForFunction(()=>window.badmintonState.baseline_camera);
  await page.screenshot({path:path.join(root,'artifacts','baseline-serve.png')});
  await page.keyboard.press('c');
  await page.waitForFunction(()=>!window.badmintonState.baseline_camera);
  await page.screenshot({path:path.join(root,'artifacts','overhead-compare.png')});
  await page.keyboard.press('c');
  await page.waitForFunction(()=>window.badmintonState.baseline_camera);
  await page.keyboard.press('h');
  await page.waitForFunction(()=>!window.badmintonState.guide);
  await page.keyboard.press('h');
  await page.waitForFunction(()=>window.badmintonState.guide);
  await page.keyboard.down('j');await page.waitForTimeout(180);await page.keyboard.up('j');
  await page.waitForFunction(()=>window.badmintonState.ball[2]>4.5);
  const high=await page.evaluate(()=>window.badmintonState);
  assert.ok(high.ball_screen[1]>110,'High shuttle must clear the scoreboard');
  await page.screenshot({path:path.join(root,'artifacts','baseline-flight.png')});
  await page.waitForFunction(()=>window.badmintonState.hits>=2,null,{timeout:8000});
  await page.waitForTimeout(250);
  await page.screenshot({path:path.join(root,'artifacts','baseline-return.png')});
  const match=await page.evaluate(()=>window.badmintonState);
  if(match.mode!=='ai'||match.hits<2)throw Error('AI did not return the serve: '+JSON.stringify(match));
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:1280,height:800});
  await page.waitForTimeout(300);
  await page.screenshot({path:path.join(root,'artifacts','pause-1280.png')});
  console.log('AI RETURN OK',match.hits);
  console.log('ERRORS',errors);
  if(errors.length)throw Error(errors.join('\n'));
  fs.writeFileSync(path.join(root,'artifacts','camera-browser-test.json'),JSON.stringify({ok:true,highBall:high.ball,highBallScreen:high.ball_screen,checks:['baseline camera','C overhead and return','H guides off/on','visible high serve','AI return','help','1280x800 pause'],errors},null,2));
  await context.close();
})().catch(e=>{console.error(e);process.exit(1)});
